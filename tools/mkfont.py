#!/usr/bin/env python3
"""Bakes the faces the kernel module draws with into kernel/font.c (and font.h): Outfit (fonts/, SIL OFL 1.1) at a few sizes and
weights, Latin-1 plus a few typographic marks, as 4-bit alpha glyphs. Needs Pillow; the output is committed, so the
build doesn't.

    python3 tools/mkfont.py
"""
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT = os.path.join(ROOT, 'fonts', 'Outfit-wght.ttf')
FACES = [  # name, size in px, weight
    ('TITLE', 32, 600),
    ('STRONG', 19, 560),
    ('BODY', 18, 400),
    ('SMALL', 15, 400),
]
CHARS = [c for c in range(0x20, 0x7F)] + [c for c in range(0xA0, 0x100)] + [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D,
                                                                            0x2026, 0x2122]

def face(size, weight):
    f = ImageFont.truetype(FONT, size)
    f.set_variation_by_axes([weight])
    return f

def main():
    data = bytearray()
    head = '/* generated by tools/mkfont.py from fonts/Outfit-wght.ttf (SIL OFL 1.1, fonts/OFL.txt): do not edit */'
    out = [head, '#include "font.h"', '']
    decl = [head, '#pragma once', '#include "draw.h"', 'extern const unsigned char FONT_DATA[];']
    for name, size, weight in FACES:
        f = face(size, weight)
        ascent, descent = f.getmetrics()
        rows = []
        for cp in CHARS:
            ch = chr(cp)
            adv = round(f.getlength(ch) * 16)
            x0, y0, x1, y1 = f.getbbox(ch, anchor='ls')
            w, h = max(0, x1 - x0), max(0, y1 - y0)
            off = len(data)
            if w and h:
                im = Image.new('L', (w, h), 0)
                ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255, anchor='ls')
                px = im.tobytes()
                for r in range(h):   # 4-bit alpha, two pixels a byte, each row starting on a byte
                    row = px[r * w:(r + 1) * w]
                    for i in range(0, w, 2):
                        a = row[i] >> 4
                        b = row[i + 1] >> 4 if i + 1 < w else 0
                        data.append(a << 4 | b)
            rows.append('{0x%04X,%d,%d,%d,%d,%d,%d}' % (cp, x0, y0, w, h, adv, off))
        out.append('static const Glyph %s_GLYPHS[%d] = {%s};' % (name, len(rows), ','.join(rows)))
        out.append('const Face FACE_%s = {%s_GLYPHS, %d, %d, %d};' % (name, name, len(rows), ascent, descent))
        decl.append('extern const Face FACE_%s;   /* %d px, weight %d */' % (name, size, weight))
    out.insert(3, 'const unsigned char FONT_DATA[%d] = {%s};' % (len(data), ','.join(str(b) for b in data)))
    with open(os.path.join(ROOT, 'kernel', 'font.c'), 'w') as fh:
        fh.write('\n'.join(out) + '\n')
    with open(os.path.join(ROOT, 'kernel', 'font.h'), 'w') as fh:
        fh.write('\n'.join(decl) + '\n')
    print('font.h: %d glyph bytes' % len(data))

if __name__ == '__main__':
    main()
